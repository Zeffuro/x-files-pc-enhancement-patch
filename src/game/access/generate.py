"""Generate named native field views from verified layout members."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def render(group):
    lines = ["// Generated by access/generate.py. Do not edit by hand.", "#pragma once",
             '#include "memory.h"']
    lines += [f'#include "{header}"' for header in group["includes"]]
    lines += ["", "namespace native_game {"]
    for obj in group["objects"]:
        name, layout = obj["name"], obj["layout"]
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*Ref", name):
            raise ValueError("Invalid view name")
        lines += [f"class {name} : public MemoryRef<{layout}> {{", "public:",
                  f"    using MemoryRef<{layout}>::MemoryRef;", ""]
        for item in obj["fields"]:
            field, offset = item["name"], item["offset"]
            if not re.fullmatch(r"[a-z][a-z0-9_]*", field):
                raise ValueError("Invalid field name")
            value = item.get("type", f'decltype({layout}::{item.get("member", field)})')
            view = item.get("view")
            arg = item.get("argument", "")
            lines += [f"    auto {field}({arg}) const {{"]
            if "build_profile->" in offset:
                lines += ["        const auto* build_profile = this->profile();"]
                target = f"build_profile ? this->offset_address({item['offset']}) : 0"
            else:
                target = f"this->offset_address({offset})"
            if item.get("before"):
                target = f"this->before_address({offset})"
            if view:
                lines += [f"        return {view}({target}, this->profile());"]
            else:
                lines += [f"        return MemoryRef<{value}>({target}, this->profile());"]
            lines += ["    }", ""]
        lines += ["};", ""]
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads((ROOT / "views.json").read_text(encoding="utf-8"))
    for name, group in catalog.items():
        target = ROOT / f"{name}.h"
        generated = render(group)
        if args.check:
            if not target.exists() or "".join(target.read_text(encoding="utf-8").split()) != "".join(generated.split()):
                raise SystemExit(f"{target.name} is stale. Run src/game/access/generate.py")
        else:
            target.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
